import React, { useState } from 'react';
import {
  View,
  Text,
  StyleSheet,
  ScrollView,
  TouchableOpacity,
  Alert,
  Linking,
} from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';
import { useTheme } from '../../shared/theme/ThemeContext';
import { Header, Card, Badge, Button, BottomSheetModal } from '../../shared/ui';
import { useAppDispatch, useAppSelector } from '../../app/store';
import { paymentSuccess, BillItem } from '../../app/store/billingSlice';
import { formatCurrency, formatLitres } from '../../shared/utils/formatters';

export const CustomerBillsScreen: React.FC<{ navigation: any }> = () => {
  const insets = useSafeAreaInsets();
  const { colors, isDark } = useTheme();
  const dispatch = useAppDispatch();
  const { bills, ledger, currentAccrued } = useAppSelector((state) => state.billing);

  const [activeTab, setActiveTab] = useState<'invoices' | 'ledger'>('invoices');
  const [selectedBill, setSelectedBill] = useState<BillItem | null>(null);
  const [isPaying, setIsPaying] = useState(false);

  const handlePayNow = (bill: BillItem) => {
    setIsPaying(true);
    // Simulate Razorpay / UPI Payment Gateway
    setTimeout(() => {
      setIsPaying(false);
      dispatch(paymentSuccess(bill.id));
      Alert.alert(
        'Payment Successful! 🎉',
        `₹${bill.netPayable} paid to Badhale Dairy via UPI. Transaction receipt generated.`
      );
      if (selectedBill?.id === bill.id) {
        setSelectedBill(null);
      }
    }, 1200);
  };

  const handleDownloadPdf = (bill: BillItem) => {
    Alert.alert(
      'Invoice PDF',
      `Downloading itemized GST invoice ${bill.invoiceNumber} generated by ReportLab.\n(Available at backend /api/billing/bills/${bill.id}/download_pdf/)`
    );
  };

  return (
    <View style={[styles.container, { backgroundColor: colors.background }]}>
      <Header
        title="Bills & Payments"
        subtitle="Post-paid monthly billing & receipts"
      />

      <ScrollView
        contentContainerStyle={[
          styles.scrollContent,
          { paddingBottom: insets.bottom + 90 },
        ]}
        showsVerticalScrollIndicator={false}
      >
        {/* Current Month Live Accrual Card */}
        <Card style={styles.accruedCard}>
          <Text style={[styles.accruedMonth, { color: colors.textSecondary }]}>
            Current Cycle • {currentAccrued.month}
          </Text>
          <Text style={[styles.accruedAmount, { color: colors.primary }]}>
            {formatCurrency(currentAccrued.amountAccrued)}
          </Text>
          <Text style={[styles.accruedSub, { color: colors.textMuted }]}>
            Accrued for {formatLitres(currentAccrued.litresDeliveredSoFar)} ({currentAccrued.daysCompleted} days delivered, {currentAccrued.daysSkipped} day skipped)
          </Text>

          <View style={styles.postpaidPill}>
            <Text style={{ fontSize: 12, color: colors.primary, fontWeight: '700' }}>
              ✓ Postpaid: Bill generates on 1st of next month
            </Text>
          </View>
        </Card>

        {/* Tab switch: Invoices vs Ledger */}
        <View style={styles.tabBar}>
          <TouchableOpacity
            onPress={() => setActiveTab('invoices')}
            style={[styles.tabItem, activeTab === 'invoices' && { backgroundColor: colors.primary }]}
          >
            <Text
              style={[
                styles.tabText,
                { color: activeTab === 'invoices' ? '#FFFFFF' : colors.textSecondary },
              ]}
            >
              Monthly Invoices
            </Text>
          </TouchableOpacity>

          <TouchableOpacity
            onPress={() => setActiveTab('ledger')}
            style={[styles.tabItem, activeTab === 'ledger' && { backgroundColor: colors.primary }]}
          >
            <Text
              style={[
                styles.tabText,
                { color: activeTab === 'ledger' ? '#FFFFFF' : colors.textSecondary },
              ]}
            >
              Account Ledger
            </Text>
          </TouchableOpacity>
        </View>

        {/* Content based on Active Tab */}
        {activeTab === 'invoices' ? (
          <View style={styles.listContainer}>
            {bills.map((bill) => {
              const isPaid = bill.status === 'paid';

              return (
                <Card key={bill.id} style={styles.billCard}>
                  <View style={styles.billHeader}>
                    <View>
                      <Text style={[styles.invoiceNo, { color: colors.textMuted }]}>
                        {bill.invoiceNumber}
                      </Text>
                      <Text style={[styles.billMonth, { color: colors.textPrimary }]}>
                        {bill.month}
                      </Text>
                    </View>
                    <Badge
                      label={bill.status.toUpperCase()}
                      variant={isPaid ? 'success' : 'warning'}
                    />
                  </View>

                  <View style={styles.billStats}>
                    <View>
                      <Text style={[styles.statLabel, { color: colors.textMuted }]}>Total Volume</Text>
                      <Text style={[styles.statVal, { color: colors.textPrimary }]}>
                        {formatLitres(bill.totalLitres)}
                      </Text>
                    </View>

                    <View>
                      <Text style={[styles.statLabel, { color: colors.textMuted }]}>Days Delivered</Text>
                      <Text style={[styles.statVal, { color: colors.textPrimary }]}>
                        {bill.deliveredDaysCount} days
                      </Text>
                    </View>

                    <View>
                      <Text style={[styles.statLabel, { color: colors.textMuted }]}>Total Amount</Text>
                      <Text style={[styles.statVal, { color: colors.primary }]}>
                        {formatCurrency(bill.netPayable)}
                      </Text>
                    </View>
                  </View>

                  <View style={styles.billActions}>
                    <TouchableOpacity
                      onPress={() => setSelectedBill(bill)}
                      style={[styles.actionBtnSecondary, { borderColor: colors.border }]}
                    >
                      <Text style={{ fontSize: 13, fontWeight: '600', color: colors.textPrimary }}>
                        View Details
                      </Text>
                    </TouchableOpacity>

                    {!isPaid ? (
                      <Button
                        title="Pay via UPI ›"
                        variant="primary"
                        size="sm"
                        onPress={() => handlePayNow(bill)}
                        loading={isPaying}
                        style={{ flex: 1 }}
                      />
                    ) : (
                      <TouchableOpacity
                        onPress={() => handleDownloadPdf(bill)}
                        style={[styles.downloadBtn, { backgroundColor: isDark ? colors.surface : '#F1F5F9' }]}
                      >
                        <Text style={{ fontSize: 13, fontWeight: '600', color: colors.primary }}>
                          📥 Download PDF
                        </Text>
                      </TouchableOpacity>
                    )}
                  </View>
                </Card>
              );
            })}
          </View>
        ) : (
          /* Ledger View */
          <View style={styles.listContainer}>
            {ledger.map((item) => {
              const isCredit = item.type === 'credit';

              return (
                <Card key={item.id} style={styles.ledgerCard} variant="outlined">
                  <View style={styles.ledgerRow}>
                    <View style={{ flex: 1 }}>
                      <Text style={[styles.ledgerDesc, { color: colors.textPrimary }]}>
                        {item.description}
                      </Text>
                      <Text style={[styles.ledgerDate, { color: colors.textMuted }]}>
                        {item.date}
                      </Text>
                    </View>

                    <View style={{ alignItems: 'flex-end' }}>
                      <Text
                        style={[
                          styles.ledgerAmount,
                          { color: isCredit ? '#10B981' : colors.textPrimary },
                        ]}
                      >
                        {isCredit ? '−' : '+'} {formatCurrency(item.amount)}
                      </Text>
                      <Text style={[styles.balanceAfter, { color: colors.textMuted }]}>
                        Bal: {formatCurrency(item.balanceAfter)}
                      </Text>
                    </View>
                  </View>
                </Card>
              );
            })}
          </View>
        )}
      </ScrollView>

      {/* Itemized Bill Detail Modal */}
      {selectedBill && (
        <BottomSheetModal
          visible={!!selectedBill}
          onClose={() => setSelectedBill(null)}
          title={`Invoice ${selectedBill.invoiceNumber}`}
          subtitle={`${selectedBill.month} • Badhale Dairy`}
        >
          <View style={styles.modalContent}>
            <View style={styles.itemizedRow}>
              <Text style={{ color: colors.textSecondary }}>Milk Deliveries ({selectedBill.totalLitres} L @ ₹{selectedBill.ratePerLitre})</Text>
              <Text style={{ fontWeight: '700', color: colors.textPrimary }}>
                {formatCurrency(selectedBill.totalLitres * selectedBill.ratePerLitre)}
              </Text>
            </View>

            {selectedBill.addonsAmount > 0 && (
              <View style={styles.itemizedRow}>
                <Text style={{ color: colors.textSecondary }}>Add-on Dairy Products</Text>
                <Text style={{ fontWeight: '700', color: colors.textPrimary }}>
                  {formatCurrency(selectedBill.addonsAmount)}
                </Text>
              </View>
            )}

            <View style={styles.itemizedRow}>
              <Text style={{ color: colors.textSecondary }}>Delivered Days</Text>
              <Text style={{ color: colors.textPrimary }}>{selectedBill.deliveredDaysCount} days</Text>
            </View>

            <View style={styles.itemizedRow}>
              <Text style={{ color: colors.textSecondary }}>Skipped Days</Text>
              <Text style={{ color: '#EF4444' }}>{selectedBill.skippedDaysCount} days (₹0 billed)</Text>
            </View>

            <View style={[styles.itemizedRow, styles.totalRow]}>
              <Text style={{ fontSize: 16, fontWeight: '800', color: colors.textPrimary }}>
                Total Net Payable
              </Text>
              <Text style={{ fontSize: 20, fontWeight: '800', color: colors.primary }}>
                {formatCurrency(selectedBill.netPayable)}
              </Text>
            </View>

            {selectedBill.status === 'unpaid' ? (
              <Button
                title="Pay with UPI / Card"
                variant="primary"
                onPress={() => handlePayNow(selectedBill)}
                loading={isPaying}
                style={{ marginTop: 20 }}
              />
            ) : (
              <Button
                title="Download Itemized PDF"
                variant="outline"
                onPress={() => handleDownloadPdf(selectedBill)}
                style={{ marginTop: 20 }}
              />
            )}
          </View>
        </BottomSheetModal>
      )}
    </View>
  );
};

